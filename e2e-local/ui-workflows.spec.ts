import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';

test('offline UI edits, W2 correction, scenarios, printable reports and complete restore', async ({ page, request }) => {
  test.setTimeout(150_000);
  page.setDefaultTimeout(15_000);
  const external: string[] = [];
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.route('**/*', route => {
    if (!route.request().url().startsWith('http://127.0.0.1:45821/')) { external.push(route.request().url()); return route.abort(); }
    return route.continue();
  });
  await page.goto('/dashboard');
  await page.getByRole('button', { name: /Add another job|Create your first job/ }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByLabel('Job name *').fill('UI employer');
  await dialog.getByLabel('Annual salary *').fill('125000');
  await dialog.getByRole('button', { name: 'Add job', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  const job = (await (await request.get('/api/jobs')).json()).find((row: { name: string }) => row.name === 'UI employer');
  expect(job).toBeTruthy();
  await page.goto(`/dashboard/jobs/${job.id}`);
  await page.getByRole('button', { name: 'Edit', exact: true }).click();
  await dialog.getByLabel('Annual salary *').focus();
  await dialog.getByLabel('Annual salary *').fill('130000');
  await dialog.getByRole('button', { name: 'Save changes', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await expect(page.locator('body')).toContainText('$130,000');

  await page.getByRole('button', { name: 'Add snapshot', exact: true }).click();
  for (const [id, value] of Object.entries({ 'paycheck-date': '2026-09-01', 'ytd-gross': '85000', 'ytd-fed': '16000', 'ytd-ss': '5270', 'ytd-med': '1232.5' })) await dialog.locator(`#${id}`).fill(value);
  await dialog.getByRole('button', { name: 'Save snapshot' }).click();
  await expect(dialog).toHaveCount(0);
  await page.getByRole('button', { name: 'Enter W2', exact: true }).click();
  for (const [id, value] of Object.entries({ box1: '120000', box2: '21000', box3: '130000', box4: '8060', box5: '130000', box6: '1885' })) { await dialog.locator(`#${id}`).focus(); await dialog.locator(`#${id}`).fill(value); }
  await dialog.getByRole('button', { name: 'Next — Box 12 codes' }).click();
  await dialog.getByRole('button', { name: 'Save W2', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  const entries = await (await request.get(`/api/w2-entries?job_id=${job.id}`)).json();
  expect(entries[0].box3_ss_wages).toBe(130000);
  expect(entries[0].box5_medicare_wages).toBe(130000);
  await page.getByRole('button', { name: 'Edit W2', exact: true }).click();
  await dialog.locator('#box2').focus();
  await dialog.locator('#box2').fill('22000');
  await dialog.locator('#correction-note').fill('Corrected Box 2 from employer statement');
  await dialog.getByRole('button', { name: 'Next — Box 12 codes' }).click();
  await dialog.getByRole('button', { name: 'Save W2', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  const corrected = (await (await request.get(`/api/w2-entries?job_id=${job.id}`)).json())[0];
  expect(corrected.box2_federal_withheld).toBe(22000);
  expect(corrected.correction_note).toBe('Corrected Box 2 from employer statement');

  await page.goto('/dashboard');
  await page.getByRole('button', { name: /2026 .*Projections/ }).click();
  await dialog.getByRole('combobox', { name: 'Filing status' }).click();
  await page.getByRole('option', { name: 'Single', exact: true }).click();
  await dialog.getByRole('button', { name: 'Save 2026 profile' }).click();
  await expect(dialog).toHaveCount(0);
  await page.getByRole('button', { name: /^(Calculate taxes|Recalculate)$/ }).first().click();
  await expect.poll(async () => (await (await request.get('/api/saved-calculations')).json()).some((row: { source: string }) => row.source === 'calculator')).toBe(true);

  await page.goto('/dashboard/scenarios');
  await page.getByRole('button', { name: 'New scenario', exact: true }).click();
  await dialog.getByRole('button', { name: 'Add Job Model adding a new W2 position' }).click();
  await dialog.getByLabel('Scenario name').fill('UI prospective employer');
  await dialog.getByPlaceholder('e.g., Acme Corp').fill('Prospective employer');
  await dialog.getByPlaceholder('85000').fill('50000');
  await dialog.getByRole('button', { name: 'Calculate Scenario' }).click();
  await expect(dialog).toHaveCount(0);
  await expect(page.getByRole('heading', { name: 'UI prospective employer' })).toBeVisible();

  await page.goto('/dashboard/benefits');
  await page.getByRole('button', { name: 'Add benefit plan', exact: true }).click();
  await dialog.getByRole('combobox').click();
  await page.getByRole('option', { name: 'UI employer', exact: true }).click();
  await dialog.getByLabel('Match %', { exact: true }).fill('100');
  await dialog.getByLabel('Cap (% of salary)', { exact: true }).fill('6');
  await dialog.getByRole('button', { name: 'Add Plan', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await page.getByRole('button', { name: 'Optimize allocations', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Recalculate', exact: true })).toBeVisible();
  await expect.poll(async () => (await (await request.get('/api/profile')).json()).profile.last_optimization_result?.allocations.length).toBeGreaterThan(0);
  await page.goto('/dashboard/tax-prep');
  await page.getByRole('button', { name: 'Add custom document' }).click();
  await page.getByPlaceholder('Document name...').fill('UI tax document');
  await page.getByRole('button', { name: 'Add', exact: true }).click();
  await expect(page.getByText('UI tax document', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Change status of UI tax document', exact: true }).click();
  await page.reload();
  await expect(page.getByText('UI tax document', { exact: true })).toBeVisible();

  await page.goto('/settings');
  await page.getByLabel('Display name').fill('UI local owner');
  await page.getByRole('button', { name: 'Save profile', exact: true }).click();
  await page.getByLabel('First name', { exact: true }).fill('UI dependent');
  await page.getByLabel('Date of birth').fill('2015-04-10');
  await page.getByRole('button', { name: 'Add dependent', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Edit UI dependent' })).toBeVisible();
  await page.getByRole('button', { name: 'Edit UI dependent' }).click();
  await page.getByLabel('First name', { exact: true }).fill('UI dependent edited');
  await page.getByRole('button', { name: 'Save dependent', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Edit UI dependent edited' })).toBeVisible();
  await page.reload();
  await expect(page.getByLabel('Display name')).toHaveValue('UI local owner');

  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('link', { name: 'Download complete backup' }).click();
  const download = await downloadEvent;
  const backupBytes = await readFile((await download.path())!);
  const backup = JSON.parse(backupBytes.toString());
  expect(Object.keys(backup.tables)).toHaveLength(11);
  await page.getByLabel('Restore backup or import existing account data (JSON)').setInputFiles({ name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from('{not json') });
  await expect(page.locator('[role=alert]').filter({ hasText: /JSON|Expected|Unexpected/ })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Reset local data', exact: true })).toBeDisabled();
  await page.getByLabel('Type DELETE to confirm reset').fill('DELETE');
  const resetReload = page.waitForEvent('framenavigated', frame => frame === page.mainFrame());
  await page.getByRole('button', { name: 'Reset local data', exact: true }).click();
  await resetReload;
  await expect.poll(async () => (await (await request.get('/api/jobs')).json()).length).toBe(0);
  await page.waitForLoadState('networkidle');
  await page.getByLabel('Restore backup or import existing account data (JSON)').setInputFiles({ name: 'complete.json', mimeType: 'application/json', buffer: backupBytes });
  await expect(page.getByRole('button', { name: 'Restore selected file' })).toBeDisabled();
  await page.getByLabel('Type RESTORE to confirm replacement').fill('RESTORE');
  const restoreReload = page.waitForEvent('framenavigated', frame => frame === page.mainFrame());
  await page.getByRole('button', { name: 'Restore selected file' }).click();
  await restoreReload;
  await expect.poll(async () => (await (await request.get('/api/jobs')).json()).some((row: { id: string }) => row.id === job.id)).toBe(true);
  await page.waitForLoadState('networkidle');
  expect((await (await request.get('/api/backup')).json()).tables).toEqual(backup.tables);

  await page.goto('/dashboard/history');
  await page.getByRole('button', { name: 'Preview and print calculation' }).first().click();
  await expect(page.getByRole('button', { name: 'Print / Save PDF' })).toBeVisible();
  await page.evaluate(() => { window.print = () => { document.body.dataset.printCalled = 'true'; }; });
  await page.getByRole('button', { name: 'Print / Save PDF' }).click();
  await expect(page.locator('body')).toHaveAttribute('data-print-called', 'true');
  await page.emulateMedia({ media: 'print' });
  await expect(page.getByRole('navigation', { name: 'Main navigation' })).not.toBeVisible();
  await page.screenshot({ path: 'test-results/local-report.png', fullPage: true });
  expect(external).toEqual([]);
  expect(errors).toEqual([]);
});
